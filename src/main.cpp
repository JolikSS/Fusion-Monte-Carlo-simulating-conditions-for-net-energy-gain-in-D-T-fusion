#include <cmath>     // математика: std::sqrt (корень), std::exp (экспонента)
#include <fstream>   // запись в файлы (нам нужно сохранить результаты в CSV)
#include <iostream>  // вывод текста в терминал (std::cout, std::cerr)
#include <random>    // генерация случайных чисел

int main()
{
    // Физические константы

    // Энергию частиц удобно измерять в кэВ (килоэлектронвольтах),
    // но формулы физики работают в джоулях. Это число - "курс перевода":
    // 1 кэВ = 1.602...e-16 джоуля. Запись e-16 означает "умножить на 10 в степени -16".
    const double keV = 1.602176634e-16;

    // Масса одного ядра дейтерия (дейтрона) в килограммах.
    // Нужна, потому что скорость частицы зависит от её массы:
    // при одной температуре лёгкие частицы летают быстрее тяжёлых.
    const double m_D = 3.3435837724e-27;

    // Температура плазмы. 10 кэВ - это примерно 116 миллионов градусов.
    const double kT_keV = 10.0;

    // Миллион частиц - достаточно,
    // чтобы гистограмма получилась гладкой.
    const int N = 1'000'000;

    // Начальное состояние генератора случайных чисел
    // С одним и тем же SEED программа каждый раз даёт одинаковый результат.
    const unsigned SEED = 42;


    // Переводим температуру из кэВ в джоули, чтобы подставлять в физические формулы.
    double kT = kT_keV * keV;

    // Скорость частицы складывается из трёх частей: по оси x, y и z.
    // Каждая часть - случайное число, распределённое по нормальному закону
    // (колоколом) вокруг нуля: частица с равными шансами летит вправо и влево.
    // sigma - "ширина колокола": насколько большие скорости типичны.
    // По физике sigma = корень(kT / m). Горячее газ - шире колокол, быстрее частицы.
    double sigma = std::sqrt(kT / m_D);

    // Создаём генератор случайных чисел.
    // mt19937 - это конкретный алгоритм (Mersenne Twister), стандартный и надёжный.
    std::mt19937 rng(SEED);

    // Создаём "нормальное распределение" со средним 0 и шириной sigma.
    // Каждый вызов normal(rng) будет выдавать новое случайное число из этого колокола.
    std::normal_distribution<double> normal(0.0, sigma);

    // записываем результат 
    std::ofstream out("maxwell.csv");

    // Проверяем, получилось ли открыть файл.
    if (!out)
    {
        std::cerr << "не удалось открыть maxwell.csv\n";
        return 1;
    }

    // Первая строка CSV-файла - заголовок столбца.
    // По нему Python потом найдёт нужные данные: df["energy_keV"].
    // \n - символ перехода на новую строку.
    out << "energy_keV\n";

    // основной цикл: создаем частицы

    // Здесь будем накапливать сумму всех энергий, чтобы потом найти среднее.
    double sum_E = 0.0;

    // Повторяем N раз: i = 0, 1, 2, ..., N-1. Каждый проход - одна новая частица.
    for (int i = 0; i < N; ++i) {

        // Генерируем три случайные составляющие скорости частицы.
        double vx = normal(rng);
        double vy = normal(rng);
        double vz = normal(rng);

        // Кинетическая энергия: E = m * v^2 / 2,
        // где v^2 = vx^2 + vy^2 + vz^2 (по теореме Пифагора в 3D).
        // Результат в джоулях делим на keV, чтобы получить энергию в кэВ.
        double E = 0.5 * m_D * (vx * vx + vy * vy + vz * vz) / keV;

        // Прибавляем энергию к общей сумме.
        sum_E += E;

        // Записываем энергию этой частицы в файл отдельной строкой.
        out << E << "\n";
    }

    // проверяем

    // Среднее = сумма / количество. По теории средняя энергия частицы
    // должна быть равна 1.5 * kT. Если числа близки - программа работает правильно.
    std::cout << "Средняя энергия: " << sum_E / N << " кэВ"
              << " (теория: " << 1.5 * kT_keV << " кэВ)\n";
    return 0;
}