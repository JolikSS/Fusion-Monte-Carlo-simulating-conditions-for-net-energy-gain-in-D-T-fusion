#include <cmath>     // std::sqrt (корень) и std::exp (экспонента)
#include <fstream>   // запись результатов в файл
#include <iostream>  // вывод текста в терминал

// Функция:вероятность туннелирования
// Здесь: даём энергию столкновения E_keV и "высоту горки" EG_keV,
// получаем вероятность того, что ядра пройдут сквозь барьер и сольются.

double tunneling_probability(double E_keV, double EG_keV)
{
    // Формула Гамова: P = exp( -корень(EG / E) ).
    // Если E маленькая, то EG / E большое, корень большой,
    // экспонента от большого отрицательного числа почти 0: шансов нет.
    // Если E большая, то EG / E маленькое, и вероятность заметно растёт.
    return std::exp(-std::sqrt(EG_keV / E_keV));
}

int main()
{
    // "Высота горки" для пары дейтерий + тритий, в кэВ.
    const double EG_DT = 1182.0;

    // открываем файл для записи результата
    std::ofstream out("tunneling.csv");

    // Проверяем, что файл открылся
    if (!out)
    {
        std::cerr << "не удалось открыть tunneling.csv\n";
        return 1;
    }

    // Заголовок таблицы: два столбца через запятую.
    // energy_keV - энергия столкновения, P_DT - вероятность слияния.
    out << "energy_keV,P_DT\n";

    // считаем вероятности для разных энергий
    // Перебираем энергии от 1 до 200 кэВ с шагом 0.5.
    // Начинаем с 1, а не с 0: при E = 0 в формуле было бы деление на ноль.
    for (double E = 1.0; E <= 200.0; E += 0.5)
    {
        // Считаем вероятность для текущей энергии.
        double P = tunneling_probability(E, EG_DT);

        // Записываем строку таблицы: энергия, запятая, вероятность.
        out << E << "," << P << "\n";
    }

    // выводим несколько чисел для проверки
    // Чтобы сразу почувствовать, насколько резко растёт вероятность.
    std::cout << "P при   1 кэВ: " << tunneling_probability(1.0, EG_DT) << "\n";
    std::cout << "P при  10 кэВ: " << tunneling_probability(10.0, EG_DT) << "\n";
    std::cout << "P при 100 кэВ: " << tunneling_probability(100.0, EG_DT) << "\n";

    return 0;
}