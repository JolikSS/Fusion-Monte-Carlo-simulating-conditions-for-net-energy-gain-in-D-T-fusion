import pandas as pd # для чтения CSV-файла
import matplotlib.pyplot as plt # для построения графика

# читаем таблицу, которую создала программа на C++
df = pd.read_csv("/home/fuf/VisualCode/fusion_sim/src/tunneling.csv")

# рисуем вероятность слияния в зависимости от энергии столкновения
plt.plot(df["energy_keV"], df["P_DT"], label="D–T")

# логарифмическая шкала по оси y: вероятность меняется от 10^-15 до 0.1,
# и в обычном масштабе вся левая часть графика слилась бы с нулём
plt.yscale("log")

plt.xlabel("Энергия столкновения, кэВ") # подпись оси x
plt.ylabel("Вероятность туннелирования") # подпись оси y
plt.title("Шанс прохождения кулоновского барьера") # заголовок
plt.legend() # подпись линии
plt.grid(True) # сетка, чтобы легче читать значения
plt.savefig("tunneling.png", dpi=150) # сохраняем картинку в файл
plt.show() # показываем график на экране